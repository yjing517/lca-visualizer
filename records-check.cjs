const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const { KEY, createStore, validateBackup } = require('./dist/records.js');
let data = {};
const storage = { getItem: k => data[k] || null, setItem: (k,v) => { data[k] = v; } };
let store = createStore(storage);
assert.equal(store.get('leetcode-236').status, '没理解');
assert.equal(store.update('leetcode-236', { notes: '<script>测试</script>\n返回的是线索', status: '需复习', review: true }), true);
store.visit('leetcode-236');
store = createStore(storage);
assert.equal(store.get('leetcode-236').notes, '<script>测试</script>\n返回的是线索');
assert.equal(store.lastVisited, 'leetcode-236');
const backup = JSON.parse(JSON.stringify(store.backup()));
assert.equal(Object.keys(validateBackup(backup)).length, 1);
assert.throws(() => validateBackup({ ...backup, version: 99 }));
assert.throws(() => validateBackup({ ...backup, records: { 'leetcode-236': { ...backup.records['leetcode-236'], review: 'yes' } } }));
assert.throws(() => validateBackup(JSON.parse('{"kind":"algorithm-notebook-backup","version":1,"records":{"__proto__":{}}}')));
store.update('other-1', { notes: '保留' });
store.update('leetcode-236', { notes: '新笔记' });
assert.ok(store.merge(validateBackup(backup)));
assert.equal(store.get('other-1').notes, '保留');
assert.equal(store.get('leetcode-236').notes, backup.records['leetcode-236'].notes);
const failed = createStore({ getItem: () => null, setItem: () => { throw Error('quota'); } });
assert.equal(failed.update('leetcode-236', { notes: '仅内存' }), false);
assert.ok(failed.error.includes('保存失败'));
assert.equal(failed.get('leetcode-236').notes, '仅内存');
assert.equal(failed.merge(validateBackup(backup)), false);
assert.equal(failed.get('leetcode-236').notes, '仅内存');
data = { [KEY]: '{broken' };
const corrupt = createStore(storage);
assert.equal(corrupt.update('leetcode-236', { notes: '不可覆盖原数据' }), false);
assert.equal(data[KEY], '{broken');
assert.equal(corrupt.merge(validateBackup(backup)), true);
assert.equal(corrupt.error, '');
const catalog = vm.runInNewContext(fs.readFileSync('dist/catalog.js', 'utf8') + ';window.PROBLEMS', { window: {} });
assert.equal(new Set(catalog.map(p => p.id)).size, catalog.length);
for (const p of catalog) {
  for (const field of ['id','number','title','difficulty','category','addedAt','summary','statement','source','complexity']) assert.equal(typeof p[field], 'string');
  assert.ok(fs.existsSync('dist/' + p.demo));
  assert.ok(p.tags.length && p.principles.length && p.pitfalls.length);
}
console.log('Passed: persistence, export/import, validation, failed writes, corruption recovery and catalog checks.');
