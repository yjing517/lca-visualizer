const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const { pathToFileURL } = require('node:url');
(async () => {
  const server = require('../../serve.cjs');
  await new Promise(r => server.listening ? r() : server.once('listening', r));
  const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || undefined, headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    const base = `http://127.0.0.1:${server.address().port}/`;
    const sandbox = { window: {} };
    vm.runInNewContext(fs.readFileSync('dist/catalog.js', 'utf8'), sandbox);
    const demos = [...sandbox.window.PROBLEMS.map(p => p.demo), 'problems/hot100-73/copy/index.html', 'problems/hot100-73/constant/index.html', 'lca.html'];
    for (const demo of demos) {
      const html = fs.readFileSync(path.join('dist', demo), 'utf8');
      const src = html.match(/<script src="([^"]*demo-keyboard.js)"><\/script>/)?.[1];
      assert.ok(src && fs.existsSync(path.resolve('dist', path.dirname(demo), src)), demo);
      await page.goto(base + demo);
      await page.locator('.keyboard-rule').waitFor();
      const read = () => page.locator('#seek').inputValue();
      const initial = await read();
      await page.locator('body').click({ position: { x: 2, y: 2 } });
      await page.keyboard.press('ArrowLeft');
      assert.equal(await read(), initial, demo + ': first boundary');
      await page.keyboard.press('ArrowRight');
      assert.equal(Number(await read()), Number(initial) + 1, demo + ': next');
      await page.keyboard.press('ArrowLeft');
      assert.equal(await read(), initial, demo + ': prev');
      const select = page.locator('#lang');
      await select.focus();
      await page.keyboard.press('ArrowRight');
      assert.equal(await read(), initial, demo + ': select protection');
      await page.locator('body').click({ position: { x: 2, y: 2 } });
      await page.keyboard.press('Control+ArrowRight');
      assert.equal(await read(), initial, demo + ': modifier protection');
      await page.locator('#seek').evaluate(el => { el.value = el.max; el.dispatchEvent(new Event('input')); });
      const last = await read();
      await page.locator('body').click({ position: { x: 2, y: 2 } });
      await page.keyboard.press('ArrowRight');
      assert.equal(await read(), last, demo + ': last boundary');
    }
    await page.goto(base + 'problems/hot100-73/optimizations.html');
    await page.frameLocator('#method-demo').locator('.keyboard-rule').waitFor();
    assert.equal(await page.locator('[data-method]').count(), 3);
    assert.equal(await page.locator('.more').getAttribute('open'), null);
    await page.locator('h1').click();
    await page.keyboard.press('ArrowRight');
    const embedded = page.frameLocator('#method-demo');
    assert.equal(await embedded.locator('#seek').inputValue(), '1');
    await embedded.locator('#reset').click();
    await embedded.locator('#speed').selectOption('350');
    await embedded.locator('#play').click();
    await page.waitForTimeout(450);
    await page.locator('h1').click();
    await page.keyboard.press('ArrowRight');
    const paused = await embedded.locator('#seek').inputValue();
    await page.waitForTimeout(500);
    assert.equal(await embedded.locator('#seek').inputValue(), paused);
    await page.screenshot({ path: 'test-results/matrix-simple-desktop.png', fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.waitForFunction(() => {
      const frame = document.getElementById('method-demo');
      return frame.contentDocument.body.scrollHeight <= frame.clientHeight + 5;
    });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.screenshot({ path: 'test-results/matrix-simple-mobile.png', fullPage: true });
    await page.goto(base + '#/problem/leetcode-73');
    await page.frameLocator('#demo').locator('.keyboard-rule').waitFor();
    await page.locator('#notes').fill('保留方向键编辑光标');
    await page.keyboard.press('ArrowLeft');
    await page.keyboard.press('ArrowRight');
    assert.equal(await page.frameLocator('#demo').locator('#seek').inputValue(), '0');
    await page.locator('h1').click();
    await page.keyboard.press('ArrowRight');
    assert.equal(await page.frameLocator('#demo').locator('#seek').inputValue(), '1');
    await page.frameLocator('#demo').locator('.matrix-extension a').click();
    const nested = page.frameLocator('#demo').frameLocator('#method-demo');
    await nested.locator('.keyboard-rule').waitFor();
    await page.locator('h1').click();
    await page.keyboard.press('ArrowRight');
    assert.equal(await nested.locator('#seek').inputValue(), '1');
    await page.goto(pathToFileURL(path.resolve('dist/problems/hot100-73/constant/index.html')).href);
    await page.locator('.keyboard-rule').waitFor();
    await page.keyboard.press('ArrowRight');
    assert.equal(await page.locator('#seek').inputValue(), '1');
    assert.deepEqual(errors, []);
    console.log(`Passed: ${demos.length} demos, keyboard steps/boundaries/edit guards, pause, notebook/nested frames, offline use and compact three-method layouts.`);
  } finally { await browser.close(); server.close(); }
})().catch(e => { console.error(e); process.exit(1); });
