const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const crypto = require("node:crypto");
const assert = require("node:assert/strict");
const profiles = require("./complexity-profiles.cjs");
const readSnippets = require("./read-snippets.cjs");
const root = path.resolve(__dirname, "..");
const sandbox = { window: {} };
vm.runInNewContext(
  fs.readFileSync(path.join(root, "dist/catalog.js"), "utf8"),
  sandbox,
);
const catalog = sandbox.window.PROBLEMS;
const signatures = {};
function validatePoint(value, label) {
  for (const key of ["bound", "when", "why"]) {
    assert.equal(typeof value?.[key], "string", `${label}.${key}`);
    assert.ok(value[key].trim().length > 0, `${label}.${key} is empty`);
  }
}
for (const problem of catalog) {
  const profile = profiles[problem.id];
  assert.ok(profile, `${problem.id}: missing complexity profile`);
  for (const key of ["algorithm", "parameters", "output"])
    assert.ok(profile[key]?.trim(), `${problem.id}.${key}`);
  for (const dimension of ["time", "space"])
    for (const kind of ["best", "worst"])
      validatePoint(
        profile[dimension]?.[kind],
        `${problem.id}.${dimension}.${kind}`,
      );
  for (const operation of profile.operations || []) {
    assert.ok(operation.name);
    validatePoint(operation.best, `${problem.id}.${operation.name}.best`);
    validatePoint(operation.worst, `${problem.id}.${operation.name}.worst`);
  }
  const script = path.join(root, "dist", path.dirname(problem.demo), "app.js");
  const snippets = readSnippets(fs.readFileSync(script, "utf8"));
  signatures[problem.id] = crypto
    .createHash("sha256")
    .update(JSON.stringify(snippets))
    .digest("hex");
}
assert.equal(
  Object.keys(profiles).length,
  catalog.length,
  "Remove stale profiles or fill missing entries",
);
const lockPath = path.join(__dirname, "complexity-code-lock.json");
if (process.argv.includes("--accept-reviewed-code"))
  fs.writeFileSync(lockPath, JSON.stringify(signatures, null, 2) + "\n");
const reviewed = JSON.parse(fs.readFileSync(lockPath, "utf8"));
assert.deepEqual(
  signatures,
  reviewed,
  "Displayed algorithms changed: review their complexity before accepting new signatures",
);
const output =
  "// Generated by node tools/build-complexity.cjs; edit tools/complexity-profiles.cjs.\nwindow.COMPLEXITY_ANALYSIS = " +
  JSON.stringify(profiles, null, 2) +
  ";\n";
const outputPath = path.join(root, "dist/complexity-data.js");
if (process.argv.includes("--check"))
  assert.equal(
    fs.readFileSync(outputPath, "utf8"),
    output,
    "Run node tools/build-complexity.cjs to refresh data",
  );
else fs.writeFileSync(outputPath, output);
console.log(
  `Passed: ${catalog.length} complexity profiles match their displayed algorithms and generated data.`,
);
